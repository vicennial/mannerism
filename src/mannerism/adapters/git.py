"""Git commit messages written by the user (author email in me.emails).

Repos come from `config["roots"]`; otherwise they are discovered from the cwd values in the newest agent transcripts
and from
direct children of ~/code, ~/src, ~/projects, ~/work, ~/dev and ~/repos. Merge commits, trailers, bot-looking messages
and
messages of two words or fewer are dropped. Without me.emails nothing is read.

R3 (P1-3, decision 4): a commit is "AI co-authored" when its message has a `Co-authored-by:` trailer naming an
agent identity (Claude, Codex, Copilot, Cursor, Gemini, Devin, aider, github-actions, a `noreply@` bot address,
an `anthropic.com`/`openai.com` address, ... the list is `[git].ai_trailers`, extending the default rather than
replacing it) or a "Generated with" line. Such commits are skipped entirely unless `[git].include_ai_commits =
true`, in which case they are kept but carry `meta.ai = true` so the bank (bank.build) still never learns from
them -- this is for completeness/visibility (status, stats), not to admit AI prose as the user's voice.

P2-16: reads use `--since` against the max committer date seen so far (tracked in the cursor), with a 3-day
overlap so a commit whose committer date moved (rebase, backdated commit) is not missed; the commit sha is
always the unit's source_ref, so the engine's normal unit_id dedup -- not this adapter -- is what makes re-seeing
a commit inside that overlap a no-op rather than a duplicate.
"""

from __future__ import annotations

import os
import re
import subprocess
from collections.abc import Iterable
from datetime import UTC, timedelta
from pathlib import Path

from ..core import Location, Me, Unit, hash_ref
from ._util import own_unit, parse_iso, transcript_cwds

TIMEOUT_S = 20
_FMT = "--format=%H%x1f%aE%x1f%aI%x1f%cI%x1f%B%x1e"
_PARENTS = ("code", "src", "projects", "work", "dev", "repos")
_TRAILER = re.compile(
    r"^(?:[A-Za-z][A-Za-z-]*-by|Change-Id|Signed-off-by|Co-authored-by|Cc|Closes|Fixes|Resolves|"
    r"Reviewed-on|Claude-Session|Link|Bug|Issue|Refs?)\s*:\s*\S",
    re.IGNORECASE,
)
_GENERATED = re.compile(r"^(?:🤖\s*)?Generated (?:with|by)\b", re.IGNORECASE)
_BOTISH = re.compile(
    r"^(?:Merge\b|Bump\b|Release\b|chore\(release\)|chore: release|v?\d+\.\d+\.\d+\s*$|"
    r"Automated\b|Auto-?generated\b|Update dependency\b|Initial commit\s*$)",
    re.IGNORECASE,
)
_CO_AUTHOR = re.compile(r"^co-authored-by\s*:\s*(.+)$", re.IGNORECASE)
DEFAULT_AI_TRAILERS = ("claude", "anthropic.com", "codex", "openai.com", "copilot", "github-actions",
                       "cursor", "gemini", "devin", "aider", "noreply@")
OVERLAP_DAYS = 3


def clean_message(msg: str) -> str:
    lines = msg.replace("\r\n", "\n").split("\n")
    while lines and (not lines[-1].strip() or _TRAILER.match(lines[-1].strip()) or _GENERATED.match(lines[-1].strip())):
        lines.pop()
    return "\n".join(lines).strip()


def is_ai_commit(body: str, needles: Iterable[str] = DEFAULT_AI_TRAILERS) -> bool:
    """A `Generated with`/`Generated by` line, or a `Co-authored-by:` trailer naming an agent identity, anywhere
    in the RAW message (before `clean_message` strips trailers -- that is exactly what this must still see)."""
    needles = [n.lower() for n in needles]
    for line in msg_lines(body):
        if _GENERATED.match(line):
            return True
        m = _CO_AUTHOR.match(line)
        if m and any(n in m.group(1).lower() for n in needles):
            return True
    return False


def msg_lines(msg: str) -> list[str]:
    return [ln.strip() for ln in msg.replace("\r\n", "\n").split("\n")]


def _is_repo(p: Path) -> bool:
    return (p / ".git").exists()


def _climb(p: Path, home: Path) -> Path | None:
    for cand in [p, *p.parents]:
        if cand == home or cand == cand.parent:
            return None
        if _is_repo(cand):
            return cand
    return None


def _git(repo: Path, *args: str) -> str | None:
    env = dict(os.environ, GIT_TERMINAL_PROMPT="0", LC_ALL="C")
    try:
        r = subprocess.run(
            ["git", "-C", str(repo), "-c", "core.quotepath=off", *args],
            capture_output=True,
            timeout=TIMEOUT_S,
            env=env,
            check=False,
        )
    except (subprocess.TimeoutExpired, OSError):
        return None
    return r.stdout.decode("utf-8", "replace") if r.returncode == 0 else None


class Git:
    name = "git"
    tier = "auto"

    def __init__(self):
        self._config: dict = {}

    def discover(self, me: Me, config: dict) -> list[Location]:
        self._config = dict(config or {})
        try:
            home = Path.home()
            repos: dict[str, Path] = {}
            roots = [Path(str(r)).expanduser() for r in (config or {}).get("roots") or []]
            if roots:
                for r in roots:
                    if _is_repo(r):
                        repos[str(r.resolve())] = r
                    elif r.is_dir():  # a folder of repos
                        for c in sorted(r.iterdir()):
                            if c.is_dir() and _is_repo(c):
                                repos[str(c.resolve())] = c
            else:
                for cwd in transcript_cwds(200, 20):
                    p = Path(cwd)
                    top = _climb(p, home) if p.is_dir() else None
                    if top is not None:
                        repos.setdefault(str(top.resolve()), top)
                for parent in _PARENTS:
                    base = home / parent
                    if base.is_dir():
                        for c in sorted(base.iterdir()):
                            if c.is_dir() and _is_repo(c):
                                repos.setdefault(str(c.resolve()), c)
            return [Location(self.name, k, v, f"git repo {v.name}") for k, v in sorted(repos.items())]
        except Exception:  # noqa: BLE001
            return []

    def read(self, loc: Location, cursor: dict | None, me: Me) -> tuple[Iterable[Unit], dict]:
        cursor = cursor or {}
        if not me.emails or loc.path is None:
            return [], cursor
        args = ["log", "--no-merges", "--all", _FMT]
        # `--since` compares against committer date (git's own default), so the cursor must track that same
        # date, not author date, or the cutoff silently drifts (P2-16). A rebase/backdated commit can still
        # move its committer date forward without us seeing it again, hence the 3-day overlap; re-seeing an
        # already-ingested commit inside that overlap is harmless because its sha (source_ref) is unchanged,
        # so the engine's own unit_id dedup is what makes it a no-op, not anything this adapter does.
        last = parse_iso(cursor.get("last_committer_ts") or cursor.get("last_ts"))
        if last is not None:
            args.insert(1, f"--since={(last - timedelta(days=OVERLAP_DAYS)).strftime('%Y-%m-%dT%H:%M:%S%z')}")
        out = _git(loc.path, *args)
        if out is None:
            return [], cursor
        own = {e.strip().lower() for e in me.emails}
        ai_trailers = [*DEFAULT_AI_TRAILERS, *(str(t) for t in (self._config.get("ai_trailers") or []))]
        include_ai = bool(self._config.get("include_ai_commits"))
        repo_hash = hash_ref(str(loc.path))
        units: list[Unit] = []
        newest = last
        for rec in out.split("\x1e"):
            rec = rec.lstrip("\n")
            parts = rec.split("\x1f", 4)
            if len(parts) < 5:
                continue
            sha_, email, a_iso, c_iso, body = parts
            ts = parse_iso(a_iso.strip())
            c_ts = parse_iso(c_iso.strip()) or ts
            if ts is None or "[bot]" in email.lower():
                continue
            if email.strip().lower() not in own:
                continue
            ts_utc = ts.astimezone(UTC)
            c_utc = (c_ts or ts).astimezone(UTC)
            if newest is None or c_utc > newest:
                newest = c_utc
            ai = is_ai_commit(body, ai_trailers)
            if ai and not include_ai:  # decision 4: skipped outright unless the user opted back in
                continue
            text = clean_message(body)
            if not text or _BOTISH.match(text) or len(text.split()) <= 2:
                continue
            meta = {"repo_hash": repo_hash}
            if ai:
                meta["ai"] = True  # kept for visibility (status/stats); bank.build() never admits it (P1-3)
            u = own_unit(
                source=self.name,
                ref=sha_.strip(),
                ts=ts_utc,
                text=text,
                kind="commit",
                register="work",
                audience="colleague",
                thread_id=repo_hash,
                meta=meta,
            )
            if u is not None:
                units.append(u)
        return units, ({"last_committer_ts": newest.isoformat()} if newest else {})
