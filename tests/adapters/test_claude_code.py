from mannerism.adapters.claude_code import ClaudeCode

from .conftest import append_jsonl, run, write_jsonl

SID = "11111111-aaaa-bbbb-cccc-222222222222"


def user(text, ts="2026-03-01T10:00:00.000Z", uuid="u1", **kw):
    d = {
        "type": "user",
        "message": {"role": "user", "content": text},
        "timestamp": ts,
        "sessionId": SID,
        "uuid": uuid,
        "cwd": "/work/demo",
    }
    d.update(kw)
    return d


def assistant(text, uuid="a1"):
    return {
        "type": "assistant",
        "message": {"role": "assistant", "content": [{"type": "text", "text": text}]},
        "timestamp": "2026-03-01T09:59:00.000Z",
        "sessionId": SID,
        "uuid": uuid,
    }


def setup(home):
    p = home / ".claude" / "projects" / "-work-demo" / f"{SID}.jsonl"
    return p


def test_filters_noise_and_keeps_own_prompts(home, me):
    p = setup(home)
    write_jsonl(
        p,
        [
            {"type": "summary", "summary": "x"},
            {"type": "file-history-snapshot", "snapshot": {}},
            assistant("Which file should I change? Mail me at bot@example.org"),
            user("please rename foo to bar, mail jo.dev@example.org", uuid="u1"),
            user("meta prompt", uuid="u2", isMeta=True),
            user("sidechain prompt", uuid="u3", isSidechain=True),
            {
                "type": "user",
                "message": {"role": "user", "content": [{"type": "tool_result", "content": "ok"}]},
                "timestamp": "2026-03-01T10:01:00Z",
                "uuid": "u4",
                "sessionId": SID,
            },
            user("<command-name>/clear</command-name>", uuid="u5"),
            user("<local-command-stdout>hi</local-command-stdout>", uuid="u6"),
            user("Caveat: The messages below were generated by the user", uuid="u7"),
            user("[Request interrupted by user]", uuid="u8"),
            user("This session is being continued from a previous conversation that ran out of context.", uuid="u9"),
            user("<system-reminder>only a reminder</system-reminder>", uuid="u10"),
            {"type": "attachment", "attachment": {"type": "x"}, "timestamp": "2026-03-01T10:00:00Z"},
            {"type": "system", "content": "boom", "timestamp": "2026-03-01T10:00:00Z"},
            user(
                [
                    {"type": "text", "text": "now run the tests"},
                    {"type": "image", "source": {}},
                    {"type": "text", "text": "<system-reminder>ignore</system-reminder>and fix the failures"},
                ],
                ts="2026-03-01T10:05:00Z",
                uuid="u11",
            ),
            user("https://example.org/page", uuid="u12"),
            "{not json",
        ],
    )
    src = ClaudeCode()
    locs = src.discover(me, {})
    assert [lc.path for lc in locs] == [p]
    units, cur = run(src, locs[0], None, me)
    assert [u.source_ref for u in units] == ["u1", "u11"]
    u = units[0]
    assert u.text == "please rename foo to bar, mail [email]"
    assert (u.kind, u.audience, u.register) == ("prompt", "agent", "agent")
    assert u.ts.tzinfo is not None and u.ts.isoformat().startswith("2026-03-01T10:00")
    assert u.context[0].who == "agent" and "[email]" in u.context[0].text
    assert "/work" not in str(u.meta) and u.meta["cwd_hash"]
    assert "SID" not in (u.thread_id or "") and SID not in (u.thread_id or "")
    assert "fix the failures" in units[1].text and "ignore" not in units[1].text and "now run" in units[1].text
    assert cur["skipped"] == 1


