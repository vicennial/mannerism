def test_reads_env_dir_and_default_dir(tmp_path, monkeypatch):
    """CLAUDE_CONFIG_DIR set in one shell must not hide the history in ~/.claude."""
    from mannerism.adapters.claude_code import ClaudeCode
    from mannerism.core import Me

    home = tmp_path / "home"
    for base in (home / ".claude", tmp_path / "wrapper"):
        d = base / "projects" / "-work-x"
        d.mkdir(parents=True)
        (d / f"{base.name}.jsonl").write_text("")
    monkeypatch.setenv("HOME", str(home))
    monkeypatch.setenv("CLAUDE_CONFIG_DIR", str(tmp_path / "wrapper"))
    names = sorted(loc.path.name for loc in ClaudeCode().discover(Me(), {}))
    assert names == [".claude.jsonl", "wrapper.jsonl"]


def test_units_carry_account_project_kind_session_and_gap(home, me):
    p = setup(home)
    write_jsonl(
        p,
        [
            assistant("done, anything else?"),  # 09:59:00
            user("please rename foo to bar in the loader module", ts="2026-03-01T10:00:00Z", uuid="m1",
                 entrypoint="cli", cwd=str(home / "work" / "demo")),
            user("and then run the tests for the loader module", ts="2026-03-01T10:00:30Z", uuid="m2",
                 entrypoint="claude-vscode", cwd="/srv/other/place"),
            user("a third prompt with an unusual entrypoint value", ts="2026-03-01T10:01:00Z", uuid="m3",
                 entrypoint="Remote"),
            user("a fourth prompt from an older version without one", ts="2026-03-01T10:02:00Z", uuid="m4", cwd=None),
        ],
    )
    src = ClaudeCode()
    units, _ = run(src, src.discover(me, {})[0], None, me)
    a, b, c, d = units
    assert a.account == "~/.claude" and a.project == "demo" and a.project_path == "~/work/demo"
    assert a.session_kind == "interactive" and a.session == a.thread_id and a.gap_s == 60.0
    assert b.session_kind == "ide" and b.project == "place" and b.project_path == "/srv/other/place"
    assert c.session_kind == "remote" and d.session_kind == "interactive" and d.project is None
    assert b.gap_s == 30.0


